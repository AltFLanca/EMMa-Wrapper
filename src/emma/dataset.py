# ── Private helpers ──────────────────────────────────────────────────────


def _ranked_probs(
    names: Sequence[str],
    probs: np.ndarray,
    *,
    threshold: float = 0.0,
    top_k: int | None = None,
) -> list[tuple[str, float]]:
    """Return ``(name, probability)`` pairs sorted descending by prob.

    Uses ``argpartition`` (O *n*) when *top_k* is given, falling back to a
    full threshold filter otherwise.
    """
    if top_k is not None:
        k = min(top_k, len(probs))
        if k == 0:
            return []
        idxs = np.argpartition(probs, -k)[-k:]
        idxs = idxs[np.argsort(probs[idxs])[::-1]]
    else:
        (idxs,) = np.where(probs >= threshold)
        idxs = idxs[np.argsort(probs[idxs])[::-1]]
    return [(names[i], float(probs[i])) for i in idxs]


# ── Main class ───────────────────────────────────────────────────────────


class EmmaDataset:
    """High-level, read-only wrapper around the EMMa v1.1 dataset.

    Loads FDD archives, search-index pickles and metadata produced by
    ``emma_completion.py``.  Exposes decoded bitfield arrays, per-category
    row indices, dataset-split boolean masks, and convenient per-record
    accessors for every stored field.

    Parameters
    ----------
    root : str or pathlib.Path
        Directory containing every EMMa data file.

    Raises
    ------
    FileNotFoundError
        If a metadata file generated by ``emma_completion.py`` is absent.

    Examples
    --------
    >>> ds = EmmaDataset("/data/emma")
    >>> rec = ds["B07XYZ1234"]
    >>> ds.get_price(rec)
    24.99
    >>> ds.get_materials(rec, top_k=3)
    [('plastic', 0.91), ('rubber', 0.07), ('metal', 0.03)]
    """

    # ------------------------------------------------------------------ #
    #  Construction                                                        #
    # ------------------------------------------------------------------ #

    def __init__(self, root: str | Path = ".") -> None:
        self._root = Path(root)

        # FDD archives
        self._fdd_dataset = FDD(str(self._root / C.DATASET_FDD))
        self._fdd_search = FDD(str(self._root / C.SEARCH_FDD))
        self._fdd_splits = FDD(str(self._root / C.SPLITS_FDD))
        self._fdd_images = FDD(str(self._root / C.IMAGES_FDD))

        # Search-index pickles
        self._category_search: dict = load_pickle(
            self._root / C.CATEGORY_SEARCH_PKL,
        )
        self.category_subtrees: dict[
            tuple[int, int], tuple[tuple[int, int], ...]
        ] = load_pickle(self._root / C.CATEGORY_HIERARCHY_PKL)["subtree"]
        self._sort_priority: dict = load_pickle(
            self._root / C.SORT_PRIORITY_PKL,
        )
        self.image_search = load_pickle(self._root / C.IMAGE_SEARCH_PKL)

        raw_price = load_pickle(self._root / C.PRICE_SEARCH_PKL)
        raw_weight = load_pickle(self._root / C.WEIGHT_SEARCH_PKL)
        raw_quantity = load_pickle(self._root / C.QUANTITY_SEARCH_PKL)
        raw_listed = load_pickle(self._root / C.LISTED_SEARCH_PKL)
        raw_material = load_pickle(self._root / C.MATERIAL_SEARCH_PKL)
        raw_custom = load_pickle(self._root / C.CUSTOM_SEARCH_PKL)
        raw_package_dimensions_present = load_npy_optional(
            self._root / C.PACKAGE_DIMENSIONS_PRESENT_NPY,
        )

        # Required metadata (from emma_completion.py)
        self.cat_id_to_name: dict[tuple[int, int], str] = (
            load_pickle_required(self._root / C.CAT_ID2NAME_PKL)
        )
        self.material_names: list[str] = load_pickle_required(
            self._root / C.MATERIAL_NAMES_PKL,
        )
        self.material_hierarchy: dict = load_json(
            self._root / C.MATERIAL_HIERARCHY_JSON,
        )
        self.custom_names: list[str] = load_pickle_required(
            self._root / C.CUSTOM_NAMES_PKL,
        )

        # Canonical ASIN vector & O(1) reverse lookup
        self.asins: np.ndarray = np.array(list(self._fdd_search.keys()))
        self.asin_to_index: dict[str, int] = {
            a: i for i, a in enumerate(self.asins)
        }

        # Case-insensitive name → index maps
        self._material_name_to_idx: dict[str, int] = {
            n.lower(): i for i, n in enumerate(self.material_names)
        }
        self._custom_name_to_idx: dict[str, int] = {
            n.lower(): i for i, n in enumerate(self.custom_names)
        }

        # Scalar numeric fields (array-level, used by the search engine)
        self.price: np.ndarray = raw_price.astype(np.float32).ravel()
        self.mass: np.ndarray = raw_weight.astype(np.float32).ravel()
        self.quantity: np.ndarray = raw_quantity.astype(np.int64).ravel()

        # Sort-priority score per row & global ranking
        n = len(self.asins)
        self.sort_score: np.ndarray = np.fromiter(
            (self._sort_priority[a] for a in self.asins),
            dtype=np.float32,
            count=n,
        )
        self.sorted_indices: np.ndarray = (
            self._load_or_build_sorted_indices()
        )
        self.priority_rank: np.ndarray = np.empty(n, dtype=np.int32)
        self.priority_rank[self.sorted_indices] = np.arange(
            n, dtype=np.int32,
        )

        # Decoded bitfields
        self.listed: ListedFlags = decode_listed(raw_listed)
        self.available: AvailabilityFlags = decode_availability_mask(
            raw_package_dimensions_present,
            n_items=n,
        )
        self.custom_bits: np.ndarray = decode_custom(raw_custom)
        self.material_bits: np.ndarray = decode_materials(
            raw_material, len(self.material_names),
        )

        # Structural indices
        self.category_indices: dict[tuple[int, int], np.ndarray] = (
            self._build_category_indices()
        )
        self.split_masks: dict[str, np.ndarray] = self._build_split_masks()

    # ------------------------------------------------------------------ #
    #  Private helpers                                                     #
    # ------------------------------------------------------------------ #

    def _load_or_build_sorted_indices(self) -> np.ndarray:
        """Load cached sort order or compute (descending by score)."""
        cached = load_npy_optional(self._root / C.SORTED_IDX_NPY)
        if cached is not None:
            return cached
        return np.argsort(self.sort_score)[::-1]

    def _build_category_indices(self) -> dict[tuple[int, int], np.ndarray]:
        lookup = self.asin_to_index
        return {
            key: np.array(
                [lookup[a] for a in asins if a in lookup],
                dtype=np.int32,
            )
            for key, asins in self._category_search.items()
        }

    def _build_split_masks(self) -> dict[str, np.ndarray]:
        n = len(self.asins)
        lookup = self.asin_to_index
        masks: dict[str, np.ndarray] = {}
        for name in self._fdd_splits.keys():
            mask = np.zeros(n, dtype=bool)
            idxs = [
                lookup[a] for a in self._fdd_splits[name] if a in lookup
            ]
            if idxs:
                mask[idxs] = True
            masks[name] = mask
        return masks

    # ------------------------------------------------------------------ #
    #  Dunder interface                                                    #
    # ------------------------------------------------------------------ #

    def __len__(self) -> int:
        return len(self.asins)

    def __contains__(self, asin: str) -> bool:
        return asin in self.asin_to_index

    def __getitem__(self, asin: str) -> dict[str, Any]:
        """Retrieve the full record for *asin*."""
        return self._fdd_dataset[asin]

    def __repr__(self) -> str:
        return (
            f"{type(self).__name__}("
            f"root={str(self._root)!r}, "
            f"n_items={len(self):,}, "
            f"n_splits={len(self.split_masks)}, "
            f"n_categories={len(self.category_indices):,})"
        )

    # ------------------------------------------------------------------ #
    #  Properties                                                          #
    # ------------------------------------------------------------------ #

    @property
    def root(self) -> Path:
        """Dataset root directory."""
        return self._root

    @property
    def split_names(self) -> list[str]:
        """Names of available dataset splits."""
        return list(self.split_masks)

    @property
    def num_materials(self) -> int:
        """Number of distinct material classes."""
        return len(self.material_names)

    @property
    def num_custom_attributes(self) -> int:
        """Number of binary custom-attribute columns."""
        return self.custom_bits.shape[1]

    # ------------------------------------------------------------------ #
    #  Record access                                                       #
    # ------------------------------------------------------------------ #

    def get_record(self, asin: str) -> dict[str, Any]:
        """Retrieve the full record dict for *asin*.

        This is the only getter that takes an ASIN.  All other
        ``get_*`` methods accept the returned dict directly.
        """
        return self._fdd_dataset[asin]

    # ------------------------------------------------------------------ #
    #  Scalar field accessors                                              #
    # ------------------------------------------------------------------ #

    @staticmethod
    def get_price(rec: dict[str, Any]) -> float:
        """Item price (USD)."""
        return float(rec[C.RecordField.PRICE])

    @staticmethod
    def get_mass(rec: dict[str, Any]) -> float:
        """Item mass (lbs)."""
        return float(rec[C.RecordField.MASS])

    @staticmethod
    def get_quantity(rec: dict[str, Any]) -> int:
        """Number of items in the listing."""
        return int(rec[C.RecordField.QUANTITY])

    @staticmethod
    def get_title(rec: dict[str, Any]) -> str:
        """Product title string."""
        return rec[C.RecordField.TITLE]

    @staticmethod
    def get_features(rec: dict[str, Any]) -> list[str]:
        """Bullet-point feature strings."""
        return rec[C.RecordField.FEATURES]

    @staticmethod
    def get_description(rec: dict[str, Any]) -> str:
        """Full product description."""
        return rec[C.RecordField.DESCRIPTION]

    @staticmethod
    def get_package_dimensions(
        rec: dict[str, Any],
    ) -> list[tuple[float, float, float]]:
        """Package dimensions as ``[(length, width, height), ...]``."""
        return rec[C.RecordField.PACKAGE_DIMENSIONS]

    @staticmethod
    def get_ratings(rec: dict[str, Any]) -> Ratings:
        """Star-rating distribution and review count.

        Returns
        -------
        Ratings
            ``.distribution`` — fraction of reviews at 1★ … 5★.
            ``.count`` — total number of reviews.
        """
        raw = rec[C.RecordField.RATINGS]
        return Ratings(distribution=tuple(raw[:5]), count=int(raw[5]))

    # ------------------------------------------------------------------ #
    #  Category accessors                                                  #
    # ------------------------------------------------------------------ #

    @staticmethod
    def get_category_ids(rec: dict[str, Any]) -> list[int]:
        """Non-negative category IDs from the record's hierarchy."""
        return [c for c in rec.get(C.RecordField.CATEGORY, []) if c >= 0]

    def get_category_names(self, rec: dict[str, Any]) -> list[str]:
        """Human-readable category names resolved via ``cat_id_to_name``.

        Each position in the record's ``category`` list is treated as a
        depth level; the ``(id, depth)`` pair is looked up in the mapping.
        IDs that are negative (padding) or absent from the mapping are
        silently skipped.
        """
        names: list[str] = []
        for depth, cid in enumerate(rec.get(C.RecordField.CATEGORY, [])):
            if cid < 0:
                continue
            name = self.cat_id_to_name.get((cid, depth))
            if name is not None:
                names.append(name)
        return names

    def get_category_path(
        self, rec: dict[str, Any],
    ) -> list[tuple[int, str]]:
        """Category hierarchy as ``[(id, name), ...]`` from root to leaf.

        Uses the same ``(id, depth)`` lookup as :meth:`get_category_names`.
        If a name is not found for a valid ID, it is recorded as ``""``.
        """
        path: list[tuple[int, str]] = []
        for depth, cid in enumerate(rec.get(C.RecordField.CATEGORY, [])):
            if cid < 0:
                continue
            name = self.cat_id_to_name.get((cid, depth), "")
            path.append((cid, name))
        return path

    # ------------------------------------------------------------------ #
    #  Material accessors                                                  #
    # ------------------------------------------------------------------ #

    @staticmethod
    def get_material_probs(rec: dict[str, Any]) -> np.ndarray:
        """Raw material-probability vector (float32)."""
        return np.asarray(rec[C.RecordField.MATERIALS], dtype=np.float32)

    def get_materials(
        self,
        rec: dict[str, Any],
        *,
        threshold: float = 0.0,
        top_k: int | None = None,
    ) -> list[tuple[str, float]]:
        """Named material probabilities, sorted descending.

        Parameters
        ----------
        rec : dict
            A record obtained from :meth:`get_record` or ``ds[asin]``.
        threshold : float
            Minimum probability to include (ignored when *top_k* is set).
        top_k : int, optional
            Return only the *k* most probable materials.

        Returns
        -------
        list of (material_name, probability)
        """
        probs = self.get_material_probs(rec)
        return _ranked_probs(
            self.material_names, probs, threshold=threshold, top_k=top_k,
        )

    def material_index(self, name: str) -> int:
        """Integer index of a material by name (case-insensitive).

        Raises :class:`KeyError` if the material is unknown.
        """
        try:
            return self._material_name_to_idx[name.lower()]
        except KeyError:
            raise KeyError(f"Unknown material: {name!r}") from None

    # ------------------------------------------------------------------ #
    #  Custom-attribute accessors                                          #
    # ------------------------------------------------------------------ #

    @staticmethod
    def get_custom_probs(rec: dict[str, Any]) -> np.ndarray:
        """Raw custom-attribute probability vector (float32)."""
        return np.asarray(rec[C.RecordField.CUSTOM], dtype=np.float32)

    def get_custom_attributes(
        self,
        rec: dict[str, Any],
        *,
        threshold: float = 0.0,
        top_k: int | None = None,
    ) -> list[tuple[str, float]]:
        """Named custom-attribute probabilities, sorted descending.

        Parameters
        ----------
        rec : dict
            A record obtained from :meth:`get_record` or ``ds[asin]``.
        threshold : float
            Minimum probability to include (ignored when *top_k* is set).
        top_k : int, optional
            Return only the *k* most probable attributes.

        Returns
        -------
        list of (attribute_name, probability)
        """
        probs = self.get_custom_probs(rec)
        return _ranked_probs(
            self.custom_names, probs, threshold=threshold, top_k=top_k,
        )

    def custom_attribute_index(self, name: str) -> int:
        """Integer index of a custom attribute by name (case-insensitive).

        Raises :class:`KeyError` if the attribute is unknown.
        """
        try:
            return self._custom_name_to_idx[name.lower()]
        except KeyError:
            raise KeyError(f"Unknown custom attribute: {name!r}") from None

    # ------------------------------------------------------------------ #
    #  Image accessors                                                     #
    # ------------------------------------------------------------------ #

    @staticmethod
    def get_image_hashes(rec: dict[str, Any]) -> list[str]:
        """Image-hash strings stored in the record."""
        return rec[C.RecordField.IMAGE_HASHES]

    def get_images(
        self,
        rec: dict[str, Any] | None = None,
        *,
        image_hashes: Sequence[str] | None = None,
    ) -> dict[str, Any]:
        """Retrieve images from the image FDD.

        Exactly one of *rec* or *image_hashes* must be provided.

        Parameters
        ----------
        rec : dict, optional
            A full record; its ``image_hashes`` field is used to look up
            every image belonging to this item.
        image_hashes : sequence of str, optional
            Explicit hash keys — they need not belong to the same record.

        Returns
        -------
        dict[str, Any]
            Mapping ``{image_hash: image_data}`` in the order requested.

        Raises
        ------
        ValueError
            If both or neither argument is supplied.
        """
        if rec is not None and image_hashes is not None:
            raise ValueError(
                "Provide 'rec' or 'image_hashes', not both.",
            )
        if rec is not None:
            image_hashes = rec[C.RecordField.IMAGE_HASHES]
        if image_hashes is None:
            raise ValueError(
                "Provide at least one of 'rec' or 'image_hashes'.",
            )
        return {h: self._fdd_images[h] for h in image_hashes}

    # ------------------------------------------------------------------ #
    #  EM-flag accessor                                                    #
    # ------------------------------------------------------------------ #

    def get_em_flags(self, rec: dict[str, Any]) -> EMFlags:
        """Decode the *filled-in-with-EM* metadata from a record.

        Returns
        -------
        EMFlags
            Per-field booleans (``True`` → value was estimated, not listed).
            The ``.materials`` attribute is a bool array of length
            :attr:`num_materials`.
        """
        raw = rec[C.RecordField.EM_FLAGS]
        mat_bytes = np.asarray(raw[0], dtype=np.uint8)
        mat_bits = np.unpackbits(mat_bytes)[: self.num_materials].astype(
            bool,
        )
        return EMFlags(
            materials=mat_bits,
            category=bool(raw[1]),
            price=bool(raw[2]),
            mass=bool(raw[3]),
            ratings=bool(raw[4]),
        )
